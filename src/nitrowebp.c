// coefficient tokens (section 13)

// Tokens of one block from position n (prob: the block type's [band][context][11]) into out
// (dequantised by dq: DC, AC; in raster order). Returns the position after the last coded
// token, 0 for an empty block: (> n) is the block's "has coefficients" context.
static int get_coeffs(Bool *b, const uint8_t (*prob)[3][11], int ctx, const int dq[2], int n, int16_t *out) {
    const uint8_t *p = prob[coeff_bands[n]][ctx];
    if (!bool_get(b, p[0])) return 0;   // end of block at once
    for (;;) {
        while (!bool_get(b, p[1])) {   // zeros
            if (++n == 16) return 16;
            p = prob[coeff_bands[n]][0];
        }
        int v, ctx2;
        if (!bool_get(b, p[2])) {
            v = 1;
            ctx2 = 1;
        } else {
            if (!bool_get(b, p[3])) {
                v = !bool_get(b, p[4]) ? 2 : 3 + bool_get(b, p[5]);
            } else if (!bool_get(b, p[6])) {
                if (!bool_get(b, p[7])) {
                    v = 5 + bool_get(b, 159);
                } else {
                    v = 7 + 2 * bool_get(b, 165);
                    v += bool_get(b, 145);
                }
            } else {
                static const uint8_t pcat3[] = {173, 148, 140, 0}, pcat4[] = {176, 155, 140, 135, 0},
                                     pcat5[] = {180, 157, 141, 134, 130, 0};
                static const uint8_t *const pcat[4] = {pcat3, pcat4, pcat5, pcat6};
                int b1 = bool_get(b, p[8]), b0 = bool_get(b, p[9 + b1]), cat = 2 * b1 + b0;
                v = 0;
                for (const uint8_t *q = pcat[cat]; *q; q++) v += v + bool_get(b, *q);
                v += 3 + (8 << cat);
            }
            ctx2 = 2;
        }
        out[zigzag[n]] = (int16_t)(bool_sign(b, v) * dq[n > 0]);
        if (++n == 16) return 16;
        p = prob[coeff_bands[n]][ctx2];
        if (!bool_get(b, p[0])) return n;   // end of block
    }
}

// ---------------------------------------------------------------------------
// reconstruction: prediction (section 12) and the inverse transforms (section 14)

#define BPS 32   // work buffer stride: a macroblock with its left column, top row and top-right pixels

static inline uint8_t clip8(int v) { return v < 0 ? 0 : v > 255 ? 255 : (uint8_t)v; }

static void inv_wht(const int16_t *in, int16_t *dc) {   // the Y2 block into the DC of the 16 Y blocks
    int t[16];
    for (int i = 0; i < 4; i++) {
        int a1 = in[i] + in[12 + i], b1 = in[4 + i] + in[8 + i], c1 = in[4 + i] - in[8 + i], d1 = in[i] - in[12 + i];
        t[i] = a1 + b1;
        t[4 + i] = c1 + d1;
        t[8 + i] = a1 - b1;
        t[12 + i] = d1 - c1;
    }
    for (int i = 0; i < 4; i++) {
        int a1 = t[4 * i] + t[4 * i + 3], b1 = t[4 * i + 1] + t[4 * i + 2], c1 = t[4 * i + 1] - t[4 * i + 2],
            d1 = t[4 * i] - t[4 * i + 3];
        dc[16 * (4 * i + 0)] = (int16_t)((a1 + b1 + 3) >> 3);
        dc[16 * (4 * i + 1)] = (int16_t)((c1 + d1 + 3) >> 3);
        dc[16 * (4 * i + 2)] = (int16_t)((a1 - b1 + 3) >> 3);
        dc[16 * (4 * i + 3)] = (int16_t)((d1 - c1 + 3) >> 3);
    }
}

#define MUL1(a) ((((a) * 20091) >> 16) + (a))   // sqrt(2) cos(pi/8)
#define MUL2(a) (((a) * 35468) >> 16)           // sqrt(2) sin(pi/8)

static void idct_add(const int16_t *in, uint8_t *dst) {   // 4x4 inverse DCT added to dst (stride BPS)
    int t[16];
    for (int i = 0; i < 4; i++) {   // vertical
        int a = in[i] + in[8 + i], b = in[i] - in[8 + i];
        int c = MUL2(in[4 + i]) - MUL1(in[12 + i]), d = MUL1(in[4 + i]) + MUL2(in[12 + i]);
        t[i] = a + d;
        t[12 + i] = a - d;
        t[4 + i] = b + c;
        t[8 + i] = b - c;
    }
    for (int i = 0; i < 4; i++) {   // horizontal
        const int *r = t + 4 * i;
        int a = r[0] + r[2], b = r[0] - r[2];
        int c = MUL2(r[1]) - MUL1(r[3]), d = MUL1(r[1]) + MUL2(r[3]);
        uint8_t *o = dst + i * BPS;
        o[0] = clip8(o[0] + ((a + d + 4) >> 3));
        o[3] = clip8(o[3] + ((a - d + 4) >> 3));
        o[1] = clip8(o[1] + ((b + c + 4) >> 3));
        o[2] = clip8(o[2] + ((b - c + 4) >> 3));
    }
}

static void dc_add(int dc, uint8_t *dst) {   // a block with only a DC coefficient
    int v = (dc + 4) >> 3;
    for (int y = 0; y < 4; y++)
        for (int x = 0; x < 4; x++) dst[y * BPS + x] = clip8(dst[y * BPS + x] + v);
}

// 16x16 / 8x8 prediction into dst (n x n; the row above at dst - BPS, the column left at dst - 1)
static void predict_block(uint8_t *dst, int n, int mode, int top, int left) {
    const uint8_t *A = dst - BPS;
    if (mode == DC_PRED) {
        int s = 0, shf = n == 16 ? 3 : 2;
        if (top)
            for (int i = 0; i < n; i++) s += A[i];
        if (left)
            for (int i = 0; i < n; i++) s += dst[i * BPS - 1];
        int v = top && left ? (s + n) >> (shf + 2) : top || left ? (s + n / 2) >> (shf + 1) : 128;
        for (int y = 0; y < n; y++) memset(dst + y * BPS, v, (size_t)n);
    } else if (mode == V_PRED) {
        for (int y = 0; y < n; y++) memcpy(dst + y * BPS, A, (size_t)n);
    } else if (mode == H_PRED) {
        for (int y = 0; y < n; y++) memset(dst + y * BPS, dst[y * BPS - 1], (size_t)n);
    } else {   // TM_PRED
        int P = A[-1];
        for (int y = 0; y < n; y++) {
            int L = dst[y * BPS - 1] - P;
            for (int x = 0; x < n; x++) dst[y * BPS + x] = clip8(L + A[x]);
        }
    }
}

#define AVG3(x, y, z) ((uint8_t)(((x) + 2 * (y) + (z) + 2) >> 2))
#define AVG2(x, y) ((uint8_t)(((x) + (y) + 1) >> 1))

static void predict_sub(uint8_t *dst, int mode) {   // 4x4 subblock (above: 8 pixels, left: 4)
    const uint8_t *A = dst - BPS;
    int P = A[-1], L[4] = {dst[-1], dst[BPS - 1], dst[2 * BPS - 1], dst[3 * BPS - 1]};
    int E[9] = {L[3], L[2], L[1], L[0], P, A[0], A[1], A[2], A[3]};
    uint8_t B[4][4];
    switch (mode) {
    case B_DC_PRED: {
        int v = 4;
        for (int i = 0; i < 4; i++) v += A[i] + L[i];
        memset(B, v >> 3, 16);
        break;
    }
    case B_TM_PRED:
        for (int r = 0; r < 4; r++)
            for (int c = 0; c < 4; c++) B[r][c] = clip8(L[r] + A[c] - P);
        break;
    case B_VE_PRED:
        for (int c = 0; c < 4; c++) B[0][c] = B[1][c] = B[2][c] = B[3][c] = AVG3(c ? A[c - 1] : P, A[c], A[c + 1]);
        break;
    case B_HE_PRED:
        for (int r = 0; r < 4; r++) {
            int v = r < 3 ? AVG3(r ? L[r - 1] : P, L[r], L[r + 1]) : AVG3(L[2], L[3], L[3]);
            B[r][0] = B[r][1] = B[r][2] = B[r][3] = (uint8_t)v;
        }
        break;
    case B_LD_PRED:
        for (int r = 0; r < 4; r++)
            for (int c = 0; c < 4; c++) {
                int k = r + c;
                B[r][c] = k < 6 ? AVG3(A[k], A[k + 1], A[k + 2]) : AVG3(A[6], A[7], A[7]);
            }
        break;
    case B_RD_PRED:
        for (int r = 0; r < 4; r++)
            for (int c = 0; c < 4; c++) {
                int k = 4 + c - r;
                B[r][c] = AVG3(E[k - 1], E[k], E[k + 1]);
            }
        break;
    case B_VR_PRED:
        B[3][0] = AVG3(E[1], E[2], E[3]);
        B[2][0] = AVG3(E[2], E[3], E[4]);
        B[3][1] = B[1][0] = AVG3(E[3], E[4], E[5]);
        B[2][1] = B[0][0] = AVG2(E[4], E[5]);
        B[3][2] = B[1][1] = AVG3(E[4], E[5], E[6]);
        B[2][2] = B[0][1] = AVG2(E[5], E[6]);
        B[3][3] = B[1][2] = AVG3(E[5], E[6], E[7]);
        B[2][3] = B[0][2] = AVG2(E[6], E[7]);
        B[1][3] = AVG3(E[6], E[7], E[8]);
        B[0][3] = AVG2(E[7], E[8]);
        break;
    case B_VL_PRED:
        B[0][0] = AVG2(A[0], A[1]);
        B[1][0] = AVG3(A[0], A[1], A[2]);
        B[2][0] = B[0][1] = AVG2(A[1], A[2]);
        B[1][1] = B[3][0] = AVG3(A[1], A[2], A[3]);
        B[2][1] = B[0][2] = AVG2(A[2], A[3]);
        B[3][1] = B[1][2] = AVG3(A[2], A[3], A[4]);
        B[2][2] = B[0][3] = AVG2(A[3], A[4]);
        B[3][2] = B[1][3] = AVG3(A[3], A[4], A[5]);
        B[2][3] = AVG3(A[4], A[5], A[6]);
        B[3][3] = AVG3(A[5], A[6], A[7]);
        break;
    case B_HD_PRED:
        B[3][0] = AVG2(E[0], E[1]);
        B[3][1] = AVG3(E[0], E[1], E[2]);
        B[2][0] = B[3][2] = AVG2(E[1], E[2]);
        B[2][1] = B[3][3] = AVG3(E[1], E[2], E[3]);
        B[2][2] = B[1][0] = AVG2(E[2], E[3]);
        B[2][3] = B[1][1] = AVG3(E[2], E[3], E[4]);
        B[1][2] = B[0][0] = AVG2(E[3], E[4]);
        B[1][3] = B[0][1] = AVG3(E[3], E[4], E[5]);
        B[0][2] = AVG3(E[4], E[5], E[6]);
        B[0][3] = AVG3(E[5], E[6], E[7]);
        break;
    default:   // B_HU_PRED
        B[0][0] = AVG2(L[0], L[1]);
        B[0][1] = AVG3(L[0], L[1], L[2]);
        B[0][2] = B[1][0] = AVG2(L[1], L[2]);
        B[0][3] = B[1][1] = AVG3(L[1], L[2], L[3]);
        B[1][2] = B[2][0] = AVG2(L[2], L[3]);
        B[1][3] = B[2][1] = AVG3(L[2], L[3], L[3]);
        B[2][2] = B[2][3] = B[3][0] = B[3][1] = B[3][2] = B[3][3] = (uint8_t)L[3];
        break;
    }
    for (int r = 0; r < 4; r++) memcpy(dst + r * BPS, B[r], 4);
}

